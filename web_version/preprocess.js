// 그린 그림을 MNIST 형식(28x28, 검은 배경에 흰 글씨, 가운데 정렬)으로 바꿉니다.
// desktop_version/app.py의 전처리()와 같은 과정을 캔버스 기능 없이 순수 자바스크립트로 구현했으므로
// 한쪽을 고치면 다른 쪽도 반드시 맞춰야 합니다.
//   글씨 영역 잘라내기 → 비율을 유지하며 긴 변을 20px로 축소(PIL LANCZOS와 같은 계산)
//   → 28x28 가운데에 배치 → 무게중심을 (14, 14)로 이동 → 정규화

// 정규화 상수 (desktop_version의 train.py, app.py와 같은 값)
export const 평균 = 0.1307, 표준편차 = 0.3081;

/** 파이썬 round()처럼 .5는 가까운 짝수로 반올림합니다. (자바스크립트 Math.round와 다름) */
function 파이썬_반올림(값) {
  const 내림 = Math.floor(값), 나머지 = 값 - 내림;
  if (나머지 !== 0.5) return 나머지 < 0.5 ? 내림 : 내림 + 1;
  return 내림 % 2 === 0 ? 내림 : 내림 + 1;
}

/** 란초시(Lanczos, a=3) 필터 */
function 란초시(x) {
  const sinc = t => (t === 0 ? 1 : Math.sin(Math.PI * t) / (Math.PI * t));
  return x > -3 && x < 3 ? sinc(x) * sinc(x / 3) : 0;
}

// PIL은 8비트 이미지를 크기 조절할 때 계수를 22비트 고정소수점으로 바꿔 계산합니다.
const 정밀도비트 = 22, 고정소수점1 = 2 ** 정밀도비트;

/** 한 축의 크기를 바꿀 때 출력 픽셀마다 쓸 입력 범위와 계수를 구합니다. (Pillow Resample.c의 precompute_coeffs) */
function 계수_계산(입력크기, 출력크기) {
  const 배율 = 입력크기 / 출력크기;
  const 필터배율 = Math.max(배율, 1);
  const 지지폭 = 3 * 필터배율;
  const 목록 = [];
  for (let 출력위치 = 0; 출력위치 < 출력크기; 출력위치++) {
    const 중심 = (출력위치 + 0.5) * 배율;
    const 시작 = Math.max(0, Math.trunc(중심 - 지지폭 + 0.5));
    const 끝 = Math.min(입력크기, Math.trunc(중심 + 지지폭 + 0.5));
    let 계수 = [];
    for (let x = 시작; x < 끝; x++) 계수.push(란초시((x - 중심 + 0.5) / 필터배율));
    const 합 = 계수.reduce((a, b) => a + b, 0);
    if (합 !== 0) 계수 = 계수.map(w => w / 합);
    // 고정소수점으로 바꿀 때 0에서 먼 쪽으로 반올림합니다.
    계수 = 계수.map(w => Math.trunc(w * 고정소수점1 + (w < 0 ? -0.5 : 0.5)));
    목록.push({ 시작, 계수 });
  }
  return 목록;
}

/** 계수로 가중합을 구하고 0~255로 자릅니다. */
function 가중합(계수, 읽기) {
  let 합 = 고정소수점1 / 2;   // 반올림용
  for (let k = 0; k < 계수.length; k++) 합 += 읽기(k) * 계수[k];
  return Math.min(255, Math.max(0, Math.floor(합 / 고정소수점1)));
}

/** 8비트 회색조 이미지를 PIL의 resize(..., Image.LANCZOS)와 같은 방식(가로 → 세로 순서)으로 크기 조절합니다. */
function 란초시_크기조절(픽셀, 가로, 세로, 새가로, 새세로) {
  let 현재 = 픽셀;
  if (새가로 !== 가로) {
    const 계수목록 = 계수_계산(가로, 새가로);
    const 결과 = new Uint8Array(새가로 * 세로);
    for (let y = 0; y < 세로; y++) {
      for (let x = 0; x < 새가로; x++) {
        const { 시작, 계수 } = 계수목록[x];
        결과[y * 새가로 + x] = 가중합(계수, k => 현재[y * 가로 + 시작 + k]);
      }
    }
    현재 = 결과;
  }
  if (새세로 !== 세로) {
    const 계수목록 = 계수_계산(세로, 새세로);
    const 결과 = new Uint8Array(새가로 * 새세로);
    for (let y = 0; y < 새세로; y++) {
      const { 시작, 계수 } = 계수목록[y];
      for (let x = 0; x < 새가로; x++) 결과[y * 새가로 + x] = 가중합(계수, k => 현재[(시작 + k) * 새가로 + x]);
    }
    현재 = 결과;
  }
  return 현재;
}

/**
 * 회색조 그림(0~255, 가로x세로 크기의 1차원 배열)을 모델 입력(정규화된 Float32Array 784개)으로 바꿉니다.
 * 아무것도 그리지 않았으면 null을 돌려줍니다.
 */
export function 전처리(회색조, 가로, 세로) {
  // 글씨가 있는 영역(0이 아닌 픽셀)만 잘라냅니다.
  let 왼 = 가로, 위 = 세로, 오른 = -1, 아래 = -1;
  for (let y = 0; y < 세로; y++) {
    for (let x = 0; x < 가로; x++) {
      if (회색조[y * 가로 + x] > 0) {
        if (x < 왼) 왼 = x;
        if (x > 오른) 오른 = x;
        if (y < 위) 위 = y;
        if (y > 아래) 아래 = y;
      }
    }
  }
  if (오른 < 0) return null;
  const 잘린가로 = 오른 - 왼 + 1, 잘린세로 = 아래 - 위 + 1;
  const 잘린그림 = new Uint8Array(잘린가로 * 잘린세로);
  for (let y = 0; y < 잘린세로; y++) {
    for (let x = 0; x < 잘린가로; x++) 잘린그림[y * 잘린가로 + x] = 회색조[(위 + y) * 가로 + 왼 + x];
  }

  // 가로세로 비율을 유지하면서 긴 변을 20픽셀로 맞춥니다.
  const 배율 = 20 / Math.max(잘린가로, 잘린세로);
  const 새가로 = Math.max(1, 파이썬_반올림(잘린가로 * 배율));
  const 새세로 = Math.max(1, 파이썬_반올림(잘린세로 * 배율));
  const 작은그림 = 란초시_크기조절(잘린그림, 잘린가로, 잘린세로, 새가로, 새세로);

  // 28x28 검은 배경의 가운데에 붙입니다.
  const 결과 = new Uint8Array(28 * 28);
  const 붙일x = Math.floor((28 - 새가로) / 2), 붙일y = Math.floor((28 - 새세로) / 2);
  for (let y = 0; y < 새세로; y++) {
    for (let x = 0; x < 새가로; x++) 결과[(붙일y + y) * 28 + 붙일x + x] = 작은그림[y * 새가로 + x];
  }

  // 무게중심이 정확히 가운데(14, 14)에 오도록 이동량을 구합니다.
  let 전체밝기 = 0, 중심x = 0, 중심y = 0;
  for (let i = 0; i < 28 * 28; i++) {
    전체밝기 += 결과[i];
    중심x += (i % 28) * 결과[i];
    중심y += Math.floor(i / 28) * 결과[i];
  }
  // 아주 작은 점은 축소하면서 모두 0이 될 수 있습니다. 이때는 이동하지 않습니다.
  const 이동x = 전체밝기 > 0 ? 파이썬_반올림(14 - 중심x / 전체밝기) : 0;
  const 이동y = 전체밝기 > 0 ? 파이썬_반올림(14 - 중심y / 전체밝기) : 0;

  // 이동한 뒤 학습 때와 같은 방식으로 정규화합니다. 밖으로 밀려난 픽셀은 버리고 빈 곳은 검은색(0)입니다.
  const 입력 = new Float32Array(28 * 28).fill((0 - 평균) / 표준편차);
  for (let y = 0; y < 28; y++) {
    for (let x = 0; x < 28; x++) {
      const 새x = x + 이동x, 새y = y + 이동y;
      if (새x >= 0 && 새x < 28 && 새y >= 0 && 새y < 28) 입력[새y * 28 + 새x] = (결과[y * 28 + x] / 255 - 평균) / 표준편차;
    }
  }
  return 입력;
}
